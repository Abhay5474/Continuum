ALTER TABLE models ADD COLUMN IF NOT EXISTS display_name        VARCHAR(160);
ALTER TABLE models ADD COLUMN IF NOT EXISTS description         TEXT;
ALTER TABLE models ADD COLUMN IF NOT EXISTS note                TEXT;
ALTER TABLE models ADD COLUMN IF NOT EXISTS max_output_tokens   INTEGER NOT NULL DEFAULT 0;
ALTER TABLE models ADD COLUMN IF NOT EXISTS provider_created_at BIGINT  NOT NULL DEFAULT 0;
ALTER TABLE models ADD COLUMN IF NOT EXISTS preview             BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE models ADD COLUMN IF NOT EXISTS status_reason       TEXT;
ALTER TABLE models ADD COLUMN IF NOT EXISTS verified_at         TIMESTAMPTZ;
ALTER TABLE models ADD COLUMN IF NOT EXISTS probe_outcome       VARCHAR(24);
ALTER TABLE models ADD COLUMN IF NOT EXISTS probed_at           TIMESTAMPTZ;
ALTER TABLE models ADD COLUMN IF NOT EXISTS limits_json         TEXT;
ALTER TABLE models ADD COLUMN IF NOT EXISTS miss_count          INTEGER NOT NULL DEFAULT 0;
ALTER TABLE models ADD COLUMN IF NOT EXISTS missing_since       TIMESTAMPTZ;
ALTER TABLE models ADD COLUMN IF NOT EXISTS retired_at          TIMESTAMPTZ;
ALTER TABLE models ADD COLUMN IF NOT EXISTS replaced_by         VARCHAR(120);
ALTER TABLE models ADD COLUMN IF NOT EXISTS first_seen_at       TIMESTAMPTZ NOT NULL DEFAULT now();
