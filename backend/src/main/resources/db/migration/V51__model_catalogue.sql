-- Per provider: when its list was last read, what it chose as the default, and
-- any model an operator pinned.
CREATE TABLE IF NOT EXISTS model_provider_state (
    provider         VARCHAR(40) PRIMARY KEY,
    last_list_ok_at  TIMESTAMPTZ,
    last_attempt_at  TIMESTAMPTZ,
    last_error       TEXT,
    listed_count     INTEGER NOT NULL DEFAULT 0,
    default_model    VARCHAR(120),
    pinned_model     VARCHAR(120),
    last_confirm_at  TIMESTAMPTZ
);

-- One row per check, scheduled or pressed, with what it cost.
CREATE TABLE IF NOT EXISTS model_check_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_kind  VARCHAR(20) NOT NULL,
    requested_by  VARCHAR(64),
    started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at   TIMESTAMPTZ,
    outcome       VARCHAR(20) NOT NULL DEFAULT 'RUNNING',
    summary       TEXT,
    list_calls    INTEGER NOT NULL DEFAULT 0,
    probe_calls   INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_model_check_runs_started ON model_check_runs (started_at DESC);

-- What changed, in order: added, verified, missing, retired, replaced.
CREATE TABLE IF NOT EXISTS model_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider    VARCHAR(40) NOT NULL,
    model_name  VARCHAR(120),
    type        VARCHAR(24) NOT NULL,
    detail      TEXT,
    run_id      BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_model_events_created ON model_events (created_at DESC);

-- One check at a time, across every instance of the backend.
CREATE TABLE IF NOT EXISTS model_check_lease (
    id           INTEGER PRIMARY KEY,
    holder       VARCHAR(64),
    acquired_at  TIMESTAMPTZ
);
